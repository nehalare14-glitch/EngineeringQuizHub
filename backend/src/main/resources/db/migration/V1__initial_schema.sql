CREATE TABLE branches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL
);

CREATE TABLE subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES branches(id),
    name VARCHAR(150) NOT NULL,
    UNIQUE (branch_id, name),
    UNIQUE (id, branch_id)
);

CREATE TABLE questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    question_text TEXT NOT NULL,
    difficulty VARCHAR(10) NOT NULL
        CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    explanation TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (subject_id, branch_id)
        REFERENCES subjects(id, branch_id)
);

CREATE TABLE question_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    option_label CHAR(1) NOT NULL
        CHECK (option_label IN ('A', 'B', 'C', 'D')),
    option_text TEXT NOT NULL,
    is_correct BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (question_id, option_label)
);

CREATE UNIQUE INDEX one_correct_option_per_question
ON question_options(question_id)
WHERE is_correct = TRUE;

CREATE TABLE user_profiles (
    firebase_uid VARCHAR(128) PRIMARY KEY,
    display_name VARCHAR(150),
    email VARCHAR(255),
    branch_id BIGINT REFERENCES branches(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE quiz_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firebase_uid VARCHAR(128) NOT NULL
        REFERENCES user_profiles(firebase_uid),
    branch_id BIGINT NOT NULL REFERENCES branches(id),
    subject_id BIGINT NOT NULL,
    difficulty VARCHAR(10) NOT NULL
        CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    total_questions INTEGER NOT NULL CHECK (total_questions > 0),
    score INTEGER CHECK (score >= 0 AND score <= total_questions),
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    FOREIGN KEY (subject_id, branch_id)
        REFERENCES subjects(id, branch_id)
);

CREATE TABLE quiz_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL
        REFERENCES quiz_attempts(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions(id),
    selected_option_id BIGINT REFERENCES question_options(id),
    is_correct BOOLEAN,
    UNIQUE (attempt_id, question_id)
);

CREATE INDEX idx_questions_filter
ON questions(branch_id, subject_id, difficulty);

CREATE INDEX idx_attempts_user
ON quiz_attempts(firebase_uid, started_at DESC);
